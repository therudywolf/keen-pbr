#!/bin/sh
# dnsmasq.sh: the conf-script entry never fails (dnsmasq would not start and the
# LAN would lose DNS) and falls back when the config cannot be generated; the
# dnsmasq restart is skipped when only the timestamp of the config-hash record
# changed.

set -u
. "$(dirname -- "$0")/lib.sh"

make_root
helper="$T/opt/usr/lib/forest-pbr/dnsmasq.sh"
install_script "$pkg_files/opt/usr/lib/forest-pbr/dnsmasq.sh" "$helper"
fallback_line="conf-file=$T/opt/etc/forest-pbr/dnsmasq-fallback.conf"
PATH="$T/opt/bin:$PATH"
export PATH

stub logger <<'EOF'
printf '%s\n' "$*" >> "$FAKE_ROOT/calls/logger"
[ ! -f "$FAKE_ROOT/fake/logger-fails" ]
EOF
stub pidof <<'EOF'
[ "$1" = dnsmasq ] && [ -f "$FAKE_ROOT/fake/dnsmasq-running" ]
EOF
cat > "$T/opt/etc/init.d/S56dnsmasq" <<'EOF'
#!/bin/sh
echo "$1" >> "$FAKE_ROOT/calls/S56dnsmasq"
EOF
chmod +x "$T/opt/etc/init.d/S56dnsmasq"

# generate-resolver-config stand-in. "$T/fake/gen" selects the outcome: ok,
# fail (half a config, then exit 1) or no-record (exit 0 without the
# config-hash record); "$T/fake/gen-hash" is the config hash it reports.
cat > "$T/opt/usr/bin/forest-pbr" <<'EOF'
#!/bin/sh
echo "$*" >> "$FAKE_ROOT/calls/forest-pbr"
mode=$(cat "$FAKE_ROOT/fake/gen")
echo "# Generated by keen-pbr (dnsmasq-ipset) - do not edit manually"
echo ""
echo "server=192.168.1.1"
echo "ipset=/example.com/kpbr4d_list,kpbr6d_list"
case "$mode" in
    fail) echo "Fatal error: RCI did not answer" >&2; exit 1 ;;
    no-record) exit 0 ;;
esac
echo "txt-record=config-hash.keen.pbr,$(date +%s%N)|$(cat "$FAKE_ROOT/fake/gen-hash")"
EOF
chmod +x "$T/opt/usr/bin/forest-pbr"
echo 0123456789abcdef0123456789abcdef > "$T/fake/gen-hash"

entry() {
    out=$("$helper" dnsmasq-config-entry 2>/dev/null)
}

# --- conf-script entry --------------------------------------------------------
echo ok > "$T/fake/gen"
entry || fail "inactive: exit code $?"
[ "$out" = "$fallback_line" ] || fail "inactive: [$out]"
[ -z "$(calls forest-pbr)" ] || fail "inactive: the config was generated"

mkdir -p "$T/tmp/forest-pbr"
echo Y > "$T/tmp/forest-pbr/active"
entry || fail "active: exit code $?"
case "$out" in
    "# Generated by keen-pbr"*"ipset=/example.com/kpbr4d_list,kpbr6d_list"*"txt-record=config-hash.keen.pbr,"*"|0123456789abcdef0123456789abcdef") ;;
    *) fail "active: generated config not passed through: [$out]" ;;
esac

for mode in fail no-record; do
    echo "$mode" > "$T/fake/gen"
    : > "$T/calls/logger"
    entry || fail "$mode: exit code $?"
    [ "$out" = "$fallback_line" ] || fail "$mode: expected only the fallback entry: [$out]"
    grep -q 'user.warn.*could not generate the dnsmasq config' "$T/calls/logger" ||
        fail "$mode: no warning logged: $(calls logger)"
done

# Even logging failing on top of it does not make the entry fail.
echo fail > "$T/fake/gen"
: > "$T/fake/logger-fails"
entry || fail "failing logger: exit code $?"
[ "$out" = "$fallback_line" ] || fail "failing logger: [$out]"
rm -f "$T/fake/logger-fails"

# --- restart only on a real change --------------------------------------------
echo ok > "$T/fake/gen"
: > "$T/fake/dnsmasq-running"
restarts() { calls S56dnsmasq | grep -c '^restart$'; }

"$helper" restart-dnsmasq 2>/dev/null || fail "restart-dnsmasq failed"
[ "$(restarts)" = 1 ] || fail "first restart-dnsmasq did not restart dnsmasq"
"$helper" restart-dnsmasq 2>/dev/null || fail "restart-dnsmasq failed"
[ "$(restarts)" = 1 ] || fail "restarted although only the record's timestamp changed"
grep -q 'resolver config unchanged, skipping dnsmasq restart' "$T/calls/logger" ||
    fail "skip not logged"

echo fedcba9876543210fedcba9876543210 > "$T/fake/gen-hash"
"$helper" reload 2>/dev/null || fail "reload failed"
[ "$(restarts)" = 2 ] || fail "a changed config did not restart dnsmasq"

rm -f "$T/fake/dnsmasq-running"
"$helper" reload 2>/dev/null || fail "reload failed"
[ "$(restarts)" = 3 ] || fail "dnsmasq not running: no restart"
: > "$T/fake/dnsmasq-running"

# Generation failing: dnsmasq gets the fallback once, not on every reload.
echo fail > "$T/fake/gen"
"$helper" reload 2>/dev/null || fail "reload failed"
[ "$(restarts)" = 4 ] || fail "switch to the fallback did not restart dnsmasq"
"$helper" reload 2>/dev/null || fail "reload failed"
[ "$(restarts)" = 4 ] || fail "restarted again on the same fallback"

# Generation works again: back to forest-pbr's config.
echo ok > "$T/fake/gen"
"$helper" reload 2>/dev/null || fail "reload failed"
[ "$(restarts)" = 5 ] || fail "recovered generation did not restart dnsmasq"

# deactivate / activate flip the state and restart dnsmasq.
"$helper" deactivate 2>/dev/null || fail "deactivate failed"
[ "$(cat "$T/tmp/forest-pbr/active")" = N ] || fail "deactivate did not mark the state inactive"
[ "$(restarts)" = 6 ] || fail "deactivate did not restart dnsmasq"
"$helper" activate 2>/dev/null || fail "activate failed"
[ "$(cat "$T/tmp/forest-pbr/active")" = Y ] || fail "activate did not mark the state active"
[ "$(restarts)" = 7 ] || fail "activate did not restart dnsmasq"

pass
